// Renders every icon in ./icon-sources.mjs once with Lucide and writes just the inner SVG markup (the
// <path>/<circle>/… elements) to src/components/home/iconPaths.generated.ts.
//
// Why: Icon.tsx used to render the full Lucide <svg> for every icon on the page — ~465 bytes each, about 93 KB
// of the 369 KB homepage HTML, almost all of it attributes repeated 200 times (xmlns, width, height, fill, stroke,
// stroke-width, linecap, linejoin, two lucide-* classes). Now those live in one CSS class (.ic in globals.css) and
// only the shapes are emitted per icon. It also takes lucide-react out of the page's JavaScript bundle.
//
// Run: `pnpm --filter @bhavano/web gen:icons`  (after adding or changing a line in icon-sources.mjs).
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import * as lucide from "lucide-react";
import { writeFileSync } from "node:fs";
import { ICON_SOURCES } from "./icon-sources.mjs";

const out = {};
for (const [name, glyph] of Object.entries(ICON_SOURCES)) {
  const Component = lucide[glyph];
  if (!Component) throw new Error(`lucide-react has no icon "${glyph}" (for "${name}")`);
  const svg = renderToStaticMarkup(createElement(Component));
  const inner = svg.slice(svg.indexOf(">") + 1, svg.lastIndexOf("</svg>"));
  if (!inner) throw new Error(`empty icon "${name}"`);
  out[name] = inner;
}

const lines = Object.entries(out).map(([name, inner]) => `  ${name}: ${JSON.stringify(inner)},`);
writeFileSync(
  new URL("../src/components/home/iconPaths.generated.ts", import.meta.url),
  `// GENERATED by scripts/generate-icon-paths.mjs from scripts/icon-sources.mjs — do not edit by hand.\n` +
    `export const ICON_PATHS = {\n${lines.join("\n")}\n} as const;\n`,
);
console.log(`wrote ${lines.length} icons`);
